"""TRACKB axis (Phase 2): strike-consistent traces from R0's top-ranked dots.

Phase 2 of the GEMS Prize rescores against labels that experts expand after
reviewing submitted faults, so this axis delivers *interpretable traces* --
polylines a structural geologist can accept, edit or reject -- rather than a
weekly-slot score probe.  It is NOT a submission candidate: the companion
raster keeps only the delivered traces' member dots, and scored as-is it
would lose most of the parent's kernel credit by construction.

Construction (all from pinned inputs, deterministic, no RNG):

  1. Rank R0's dots by *strand credit*: the triangular-kernel (R = 3 px)
     credit a dot claims on h19_5 ridge pixels where it is the nearest dot
     (the max-operator term of the DTI algebra, restricted to the parent's
     own ridge field).  A flat-prior unique-credit ranking (gemsdoe.mass)
     was tried first and rejected on measurement: its top half is mostly
     isolated dots and fragments every strand (largest linked component
     9 dots at 4.5 px linking, vs 170 under strand credit).
  2. Candidate dots = top two-thirds by strand credit.  Link dots within
     4.5 px (KDTree graph) into connected components.
  3. Order each component's dots by graph-geodesic arc coordinate
     (Dijkstra from a diameter endpoint), giving the trace polyline.
  4. A trace qualifies if: polyline length >= 1 km, >= 8 member dots,
     strike consistency R >= 0.85 (mean resultant length of doubled
     segment azimuths; 1.0 = perfectly collinear segments) and
     straightness (chord / path) >= 0.60.
  5. Delivered traces = the top 12 qualifying traces by total member
     strand credit.  One evidence paragraph per delivered trace is
     generated by tools/build_trackb.py into ledger/TRACKB_TRACES.md.

Strike is reported as a geological strike azimuth (0-180 deg, from the
first principal component in east/north map coordinates).  All member
dots are R0 dots, so the raster inherits the parent's catalogue
clearance (min d_cat > 2 px) and zero catalogue mass.
"""

from __future__ import annotations

import heapq

import numpy as np
from scipy import ndimage as ndi
from scipy.spatial import cKDTree

KERNEL_RADIUS_PX = 3.0
CREDIT_KEEP_FRACTION = 2.0 / 3.0
LINK_PX = 4.5
MIN_LENGTH_KM = 1.0
MIN_DOTS = 8
MIN_CONSISTENCY_R = 0.85
MIN_STRAIGHTNESS = 0.60
TOP_N = 12
PX_KM = 0.1  # 100 m pixels


def strand_credit(dots, field_mask, radius=KERNEL_RADIUS_PX):
    """Per-dot kernel credit claimed on `field_mask` pixels (nearest dot wins).

    Returns (credit, pts).  Ties in nearest-dot assignment are broken by
    the EDT index order (deterministic); this is a ranking, not a score.
    """
    dots = np.asarray(dots, dtype=bool)
    pts = np.argwhere(dots)
    dist, idx = ndi.distance_transform_edt(~dots, return_indices=True)
    flat_id = -np.ones(dots.size, dtype=np.int64)
    flat_id[pts[:, 0] * dots.shape[1] + pts[:, 1]] = np.arange(len(pts))
    nearest_dot = flat_id[(idx[0] * dots.shape[1] + idx[1]).ravel()]
    k = np.clip(1.0 - dist / radius, 0.0, None)
    sel = ((dist <= radius) & np.asarray(field_mask, dtype=bool)).ravel()
    credit = np.zeros(len(pts), dtype=np.float64)
    np.add.at(credit, nearest_dot[sel], k.ravel()[sel])
    return credit, pts


def linked_components(pts, link_px=LINK_PX):
    """Connected components of the <= link_px dot graph (union-find)."""
    pts = np.asarray(pts)
    parent = list(range(len(pts)))

    def find(a):
        while parent[a] != a:
            parent[a] = parent[parent[a]]
            a = parent[a]
        return a

    for i, j in cKDTree(pts).query_pairs(link_px):
        ri, rj = find(i), find(j)
        if ri != rj:
            parent[ri] = rj
    comps: dict[int, list[int]] = {}
    for i in range(len(pts)):
        comps.setdefault(find(i), []).append(i)
    return [np.array(sorted(v), dtype=np.int64) for v in comps.values()]


def arc_order(pts, link_px=LINK_PX):
    """Order pts along the dot graph by geodesic distance from a diameter end."""
    pts = np.asarray(pts, dtype=np.float64)
    n = len(pts)
    if n <= 2:
        return np.arange(n), np.zeros(n)
    adj: list[list[tuple[int, float]]] = [[] for _ in range(n)]
    for i, j in cKDTree(pts).query_pairs(link_px):
        w = float(np.hypot(pts[i, 0] - pts[j, 0], pts[i, 1] - pts[j, 1]))
        adj[i].append((j, w))
        adj[j].append((i, w))

    def dijkstra(src):
        dist = np.full(n, np.inf)
        dist[src] = 0.0
        pq = [(0.0, src)]
        while pq:
            d, u = heapq.heappop(pq)
            if d > dist[u]:
                continue
            for v, w in adj[u]:
                nd = d + w
                if nd < dist[v]:
                    dist[v] = nd
                    heapq.heappush(pq, (nd, v))
        return dist

    end_a = int(np.argmax(np.where(np.isfinite(dijkstra(0)), dijkstra(0), -1)))
    s = dijkstra(end_a)
    s = np.where(np.isfinite(s), s, np.hypot(pts[:, 0] - pts[end_a, 0],
                                             pts[:, 1] - pts[end_a, 1]) + (s[np.isfinite(s)].max() if np.isfinite(s).any() else 0.0))
    order = np.lexsort((pts[:, 1], pts[:, 0], s))
    return order, s[order]


def _azimuth_deg(dx_east, dy_north):
    """Geological strike azimuth in [0, 180) from an east/north vector."""
    return float(np.degrees(np.arctan2(dx_east, dy_north)) % 180.0)


def trace_metrics(ordered_pts, member_credit, d_cat):
    """Geometry of one ordered trace. ordered_pts are (row, col) pixels."""
    p = np.asarray(ordered_pts, dtype=np.float64)
    east = p[:, 1]
    north = -p[:, 0]
    en = np.column_stack([east, north])
    seg = np.diff(en, axis=0)
    seg_len = np.hypot(seg[:, 0], seg[:, 1])
    path_px = float(seg_len.sum())
    chord_px = float(np.hypot(*(en[-1] - en[0]))) if len(en) > 1 else 0.0
    # strike from first principal component
    cen = en - en.mean(axis=0)
    _, _, vt = np.linalg.svd(cen, full_matrices=False)
    strike = _azimuth_deg(vt[0, 0], vt[0, 1])
    # strike consistency: resultant length of doubled segment azimuths
    if len(seg):
        ang = np.arctan2(seg[:, 0], seg[:, 1])  # azimuth from north
        R = float(np.abs(np.exp(2j * ang).mean()))
        seg_az = np.degrees(ang) % 180.0
        dev = np.abs((seg_az - strike + 90.0) % 180.0 - 90.0)
        mean_dev = float(np.average(dev, weights=seg_len)) if seg_len.sum() else 0.0
    else:
        R, mean_dev = 1.0, 0.0
    d = d_cat[np.asarray(ordered_pts)[:, 0].astype(int), np.asarray(ordered_pts)[:, 1].astype(int)]
    return {
        "n_dots": int(len(p)),
        "length_km": path_px * PX_KM,
        "chord_km": chord_px * PX_KM,
        "straightness": float(chord_px / path_px) if path_px else 0.0,
        "strike_deg": strike,
        "consistency_R": R,
        "mean_segment_deviation_deg": mean_dev,
        "mean_spacing_px": float(seg_len.mean()) if len(seg_len) else 0.0,
        "credit_sum": float(np.sum(member_credit)),
        "credit_mean": float(np.mean(member_credit)),
        "dcat_min_px": float(d.min()),
        "dcat_mean_px": float(d.mean()),
    }


def build_traces(dots, field_mask, d_cat, top_n=TOP_N,
                 keep_fraction=CREDIT_KEEP_FRACTION, link_px=LINK_PX):
    """Return (delivered_traces, audit). Each trace: ordered pts + metrics."""
    credit, pts = strand_credit(dots, field_mask)
    thr = float(np.quantile(credit, 1.0 - keep_fraction))
    cand = credit >= thr
    cand_idx = np.flatnonzero(cand)
    comps = linked_components(pts[cand], link_px)
    qualifying = []
    n_comp_ge_min = 0
    for comp in comps:
        if len(comp) < MIN_DOTS:
            continue
        n_comp_ge_min += 1
        member = cand_idx[comp]
        order, _ = arc_order(pts[member], link_px)
        member = member[order]
        m = trace_metrics(pts[member], credit[member], d_cat)
        if (m["length_km"] >= MIN_LENGTH_KM and m["consistency_R"] >= MIN_CONSISTENCY_R
                and m["straightness"] >= MIN_STRAIGHTNESS):
            qualifying.append({"member_idx": member, "pts": pts[member], "metrics": m})
    qualifying.sort(key=lambda t: (-t["metrics"]["credit_sum"],
                                   -t["metrics"]["length_km"],
                                   int(t["pts"][0, 0]), int(t["pts"][0, 1])))
    delivered = qualifying[:top_n]
    for i, t in enumerate(delivered, 1):
        t["trace_id"] = f"T{i:02d}"
    audit = {
        "credit_threshold": thr,
        "n_candidate_dots": int(cand.sum()),
        "n_components": int(len(comps)),
        "n_components_ge_min_dots": int(n_comp_ge_min),
        "n_qualifying_traces": int(len(qualifying)),
        "n_delivered_traces": int(len(delivered)),
        "criteria": {"min_length_km": MIN_LENGTH_KM, "min_dots": MIN_DOTS,
                     "min_consistency_R": MIN_CONSISTENCY_R,
                     "min_straightness": MIN_STRAIGHTNESS,
                     "link_px": link_px, "keep_fraction": keep_fraction},
    }
    return delivered, audit, credit, pts
